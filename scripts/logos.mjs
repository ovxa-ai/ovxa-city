// Regenerates src/logos.ts from @lobehub/icons-static-svg (MIT). Run: node scripts/logos.mjs
import { readFileSync, writeFileSync } from 'node:fs';
const MAP = { openai: 'openai', grokbot: 'grokbot', grok: 'grok', xai: 'xai', claude: 'claude', anthropic: 'anthropic', cursor: 'cursor', gemini: 'gemini', openclaw: 'openclaw', muse: 'muse', langchain: 'langchain', crewai: 'crewai', n8n: 'n8n', mcp: 'mcp', copilot: 'githubcopilot', windsurf: 'windsurf' };
const out = {};
for (const [k, f] of Object.entries(MAP)) {
  let s = readFileSync(`node_modules/@lobehub/icons-static-svg/icons/${f}.svg`, 'utf8');
  const rule = /fill-rule="evenodd"/.test(s.slice(0, s.indexOf('>'))) ? ' fill-rule="evenodd"' : '';
  s = s.replace(/^<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').replace(/<title>.*?<\/title>/, '')
    .replace(/<defs>.*?<\/defs>/g, '').replace(/<g clip-path="[^"]*">/g, '<g>').replace(/><\/path>/g, '/>');
  if (/url\(#/.test(s)) throw new Error('unresolved ref in ' + f);
  out[k] = `<g fill="currentColor"${rule}>${s}</g>`;
}
writeFileSync('src/logos.ts', `/** Official brand marks (24×24, currentColor) generated by scripts/logos.mjs from @lobehub/icons-static-svg (MIT). Trademarks belong to their owners. */\nexport const LOGO: Record<string, string> = ${JSON.stringify(out, null, 1)};\n`);
console.log(Object.keys(out).length, 'logos');
